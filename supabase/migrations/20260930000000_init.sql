-- =====================================================================
-- Paradise City Rooms — database setup
--
-- Run this whole file once in Supabase → SQL Editor → "New query" → Run.
--
-- Rules enforced here (the website shows the same rules, but the
-- database is the final judge, so nobody can bypass them):
--   * Only @paradisecity.be addresses can create an account.
--   * quinten@paradisecity.be automatically becomes admin.
--   * Bookings: 15-minute steps, between 07:00 and 20:00 (Brussels time),
--     not in the past, at most 3 months ahead, never overlapping.
-- =====================================================================

create extension if not exists btree_gist with schema extensions;

-- ---------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text not null unique,
  full_name text not null check (char_length(full_name) between 1 and 100),
  role text not null default 'member' check (role in ('member', 'admin')),
  blocked boolean not null default false,
  theme jsonb,
  created_at timestamptz not null default now()
);

create table public.rooms (
  id smallint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 1 and 60),
  capacity integer not null check (capacity between 1 and 500),
  color text not null default '#6366f1' check (color ~ '^#[0-9a-fA-F]{6}$'),
  sort_order integer not null default 0
);

